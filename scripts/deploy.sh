#!/usr/bin/env bash
# Install or update the bot. Safe to re-run: it creates only what is missing.
#
#   scripts/deploy.sh            upload the code, settings from config.env and questions.json
#   scripts/deploy.sh --token    also ask for the bot token: first install, token rotation,
#                                or a different GROUP in config.env
#   scripts/deploy.sh --dry-run  check settings and questions and build, without uploading
# shellcheck source=scripts/lib.sh
source "$(dirname "$0")/lib.sh"

with_token=false dry_run=false
for arg in "$@"; do
  case $arg in
    --token) with_token=true ;;
    --dry-run) dry_run=true ;;
    *) die "неизвестный параметр $arg (есть --token и --dry-run)" ;;
  esac
done

need curl jq
load_config
questions=$(validate_questions questions.json)
info "Вопросы: $(jq -r '[.questions[].id] | join(", ")' <<<"$questions")"

if ! $dry_run; then
  [[ -n ${CHAT_ID:-} ]] || with_token=true # first install
  [[ $with_token == true || ${CHAT_GROUP:-} == "$GROUP" ]] ||
    die "GROUP в config.env изменился — запустите scripts/deploy.sh --token"
fi

# --- Telegram: bot, group and the bot's rights there -------------------------
if $with_token && ! $dry_run; then
  ask_token
  me=$(tg getMe)
  bot_id=$(jq .id <<<"$me")
  save_state BOT_USERNAME "$(jq -r .username <<<"$me")"
  info "Бот: @$BOT_USERNAME"

  chat=$(tg getChat "$(jq -nc --arg c "$GROUP" '{chat_id: $c}')")
  [[ $(jq -r .type <<<"$chat") == supergroup ]] ||
    die "$GROUP — не супергруппа. Включите в настройках группы «История чата: видна» — Telegram преобразует её в супергруппу"
  [[ $(jq -r '.join_by_request // false' <<<"$chat") == false ]] ||
    die "в группе включены заявки на вступление — выключите «Одобрение новых участников»"
  save_state CHAT_ID "$(jq -r .id <<<"$chat")"
  save_state CHAT_GROUP "$GROUP"
  info "Группа: $(jq -r .title <<<"$chat") ($CHAT_ID), темы: $(jq -r '.is_forum // false' <<<"$chat")"

  rights=$(tg getChatMember "$(jq -nc --arg c "$CHAT_ID" --argjson u "$bot_id" '{chat_id: $c, user_id: $u}')")
  [[ $(jq -r .status <<<"$rights") == administrator &&
    $(jq -r '.can_delete_messages and .can_restrict_members' <<<"$rights") == true ]] ||
    die "бот должен быть администратором группы с правами «Удаление сообщений» и «Блокировка пользователей»"
fi

# --- Cloudflare: database, config, deploy -----------------------------------
db_id() {
  wrangler d1 list --json 2>/dev/null | jq -r --arg n "$WORKER_NAME" '.[] | select(.name == $n) | .uuid'
}

if $dry_run; then
  database_id=${DATABASE_ID:-00000000-0000-0000-0000-000000000000}
else
  database_id=$(db_id)
  if [[ -z $database_id ]]; then
    info "Создаю базу данных $WORKER_NAME"
    wrangler d1 create "$WORKER_NAME" </dev/null >&2
    database_id=$(db_id)
    [[ -n $database_id ]] || die "база создана, но не найдена в списке — запустите скрипт ещё раз"
  fi
  save_state DATABASE_ID "$database_id"
  [[ -n ${WEBHOOK_SECRET:-} ]] || save_state WEBHOOK_SECRET "$(head -c 32 /dev/urandom | od -An -tx1 | tr -d ' \n')"
fi

# The prompt must go before Telegram's 48 h limit on deleting messages; the hourly
# sweep deletes it between 46 and 47 h at the latest.
remove_after=$((REMOVE_AFTER_HOURS * 3600))
prompt_ttl=$((remove_after < 46 * 3600 ? remove_after : 46 * 3600))

{
  echo "// Generated by scripts/deploy.sh from config.env: edit config.env, not this file."
  jq -n \
    --arg name "$WORKER_NAME" --arg db "$database_id" \
    --arg chat "${CHAT_ID:--1000000000000}" --arg bot "${BOT_USERNAME:-example_bot}" \
    --arg max "$MAX_ATTEMPTS" --arg rate "$OBFUSCATE_RATE" --arg thread "$PROMPT_THREAD_ID" \
    --arg ttl "$prompt_ttl" --arg remove "$remove_after" '{
      name: $name,
      main: "src/index.ts",
      compatibility_date: "2026-09-01",
      observability: { enabled: true },
      d1_databases: [{ binding: "DB", database_name: $name, database_id: $db }],
      vars: {
        CHAT_ID: $chat, BOT_USERNAME: $bot, MAX_ATTEMPTS: $max, OBFUSCATE_RATE: $rate,
        PROMPT_THREAD_ID: $thread, PROMPT_TTL_SEC: $ttl, REMOVE_AFTER_SEC: $remove
      },
      triggers: { crons: ["0 * * * *"] }
    }'
} > wrangler.jsonc

if $dry_run; then
  wrangler deploy --dry-run >&2
  info "Проверка пройдена, ничего не загружено."
  exit 0
fi

info "Обновляю схему базы"
d1 --file schema.sql >/dev/null

secrets=$(mktemp)
trap 'rm -f "$secrets"' EXIT
jq -n --arg w "$WEBHOOK_SECRET" --arg q "$questions" --arg t "${BOT_TOKEN:-}" \
  '{ WEBHOOK_SECRET: $w, QUESTIONS: $q } + (if $t == "" then {} else { BOT_TOKEN: $t } end)' > "$secrets"

info "Загружаю бота в Cloudflare"
out=$(wrangler deploy --secrets-file "$secrets" 2>&1) || { echo "$out" >&2; die "wrangler deploy не удался"; }
url=$(grep -o 'https://[a-z0-9.-]*\.workers\.dev' <<<"$out" | head -1)
[[ -n $url ]] || { echo "$out" >&2; die "не нашёл адрес воркера в выводе wrangler"; }
save_state WORKER_URL "$url"
info "Адрес: $WORKER_URL"

info "Подключаю вебхук Telegram"
# A fresh deployment can take a few seconds to answer.
for try in 1 2 3 4 5 6; do
  setup=$(worker setup) && jq -e .bot <<<"$setup" >/dev/null 2>&1 && break
  [[ $try == 6 ]] && die "ответ /setup: $setup"
  sleep 5
done
jq . <<<"$setup"
jq -e '.status_in_group == "administrator" and .can_delete_messages and .can_restrict_members' <<<"$setup" >/dev/null ||
  die "у бота нет нужных прав в группе"
info "Готово. Бот работает в группе."
